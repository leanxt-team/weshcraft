// Writes src/web/public/techicons.js: the brand marks the technology catalog uses, taken from
// Simple Icons (CC0 1.0, https://simpleicons.org). Run after changing the catalog:
//   npm i --no-save simple-icons@16 && node scripts/build-tech-icons.mjs
// Only the marks the catalog names are kept (path + colour), so the app carries a few dozen KB.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const here = path.dirname(new URL(import.meta.url).pathname);
const out = path.join(here, '../src/web/public/techicons.js');
const from = process.argv[2] ? createRequire(path.resolve(process.argv[2], 'package.json')) : createRequire(import.meta.url);
const si = from('simple-icons');
const siDir = path.dirname(from.resolve('simple-icons'));
const siVersion = JSON.parse(fs.readFileSync(path.join(siDir, 'package.json'), 'utf8')).version;
fs.writeFileSync(out, 'export const BRAND = {};\n'); // the catalog imports it; filled below
const { TECH } = await import(path.join(here, '../src/web/public/techcatalog.js'));
const keys = [...new Set([...TECH.map(e => e.si).filter(Boolean), 'googlecloud'])].sort();
const BRAND = {};
const missing = [];
for (const k of keys) {
  const ic = si[`si${k[0].toUpperCase()}${k.slice(1)}`];
  if (!ic) { missing.push(k); continue; }
  BRAND[k] = { hex: ic.hex, path: ic.path.replace(/(\.\d)\d+/g, '$1') }; // one decimal is plenty at icon size
}
fs.writeFileSync(out, `// Brand marks for the technology catalog (techcatalog.js), from Simple Icons ${siVersion}
// (https://simpleicons.org), CC0 1.0. Generated by scripts/build-tech-icons.mjs: do not edit.
// The marks are trademarks of their owners, shown to name the technology a component uses.
export const BRAND = ${JSON.stringify(BRAND)};
`);
console.log(`${Object.keys(BRAND).length} marks → ${path.relative(process.cwd(), out)}${missing.length ? `\nnot in Simple Icons (shown as a badge instead): ${missing.join(' ')}` : ''}`);
