import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { startHost } from './host.mjs';
const [ROOT, WORK] = process.argv.slice(2);
const { chromium } = createRequire(import.meta.url)('playwright');
fs.rmSync(WORK, { recursive: true, force: true });
const P = path.join(WORK, 'pub'); fs.mkdirSync(path.join(P, 'design'), { recursive: true });
fs.copyFileSync(path.join(ROOT, 'test/fixtures/account.figcraft.json'), path.join(P, 'design/account.figcraft.json'));
execSync('git init -q && git config user.email t@e.com && git config user.name T && git commit -q --allow-empty -m init', { cwd: P, shell: '/bin/sh' });
const { createService, listen } = await import(path.join(ROOT, 'openchamber/service/main.js'));
const service = createService(); const s = listen({ port: 47992, token: 't', service });
const host = await startHost({ root: ROOT, sdkDir: path.join(ROOT, 'node_modules/@openchamber/sdk'), service: { port: 47992, token: 't' } });
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1300, height: 860 } });
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && !/fonts\.g/.test(m.text()) && errs.push(m.text()));
await p.goto(`${host.url}/host?entry=openchamber/page/index.html&dir=${encodeURIComponent(P)}&w=1280&h=840&surface=page`);
const f = p.frameLocator('#f');
await f.locator('#publish').waitFor({ timeout: 30000 });
for (let i = 0; i < 60 && !/In sync/.test(await f.locator('#parity').innerText()); i++) await p.waitForTimeout(300);
await f.locator('#publish').click(); await p.waitForTimeout(400);
await f.locator('#publishForm label:has(input[value="git"])').click(); await p.waitForTimeout(200);
await p.screenshot({ path: path.join(WORK, 'publish-dialog.png') });
await f.locator('#publishGo').click();
let log = '';
for (let i = 0; i < 40; i++) { log = execSync('git log --oneline', { cwd: P }).toString(); if (/docs\(specs\)/.test(log)) break; await p.waitForTimeout(300); }
console.log(/docs\(specs\)/.test(log) ? 'PASS' : 'FAIL', 'publish dialog (sandboxed form) commits to local git —', log.split('\n')[0]);
console.log((await f.locator('#publishResult').innerText().catch(() => '')).slice(0, 120));
const pill = await f.locator('#syncPill').innerText();
console.log(/git/.test(pill) ? 'PASS' : 'FAIL', 'sync pill shows the target —', pill);
console.log(errs.length ? `FAIL errors ${errs.join(' | ')}` : 'PASS no errors');
await b.close(); service.stop(); s.close(); host.close(); setTimeout(() => process.exit(0), 300);
