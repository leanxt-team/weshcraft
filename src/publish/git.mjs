// Publish the prototype and specs to GitHub (pull request) or GitLab (merge request) through
// their REST APIs: one commit on a branch, then a PR/MR whose description carries the parity
// summary. Nothing is force-pushed; an existing branch gets a new commit on top.
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
import { ciFiles } from './ci.mjs';

const TEXT = new Set(['.md', '.json', '.html', '.css', '.yml', '.yaml', '.txt', '.js', '.mjs', '.svg']);

/** Files to publish: everything WeshCraft wrote under outDir, plus CI and the design source. */
export function collectFiles(outDir, { designFile, designInputs, prefix = '', ci = true, provider = 'github', designPath } = {}) {
  const files = [];
  const walk = dir => {
    for (const e of fs.readdirSync(path.join(outDir, dir), { withFileTypes: true })) {
      const rel = path.posix.join(dir, e.name);
      if (e.isDirectory()) walk(rel);
      else files.push({ path: path.posix.join(prefix, rel), data: fs.readFileSync(path.join(outDir, rel)) });
    }
  };
  for (const d of ['prototype', 'specs']) if (fs.existsSync(path.join(outDir, d))) walk(d);
  // Design inputs (a .figcraft, OpenAPI, MCP tool lists, surface files) go to design/ by name.
  const inputs = designInputs ?? (designFile ? [{ abs: designFile, arg: '--file' }] : []);
  const args = [];
  const seen = new Set();
  for (const x of inputs) {
    if (!fs.existsSync(x.abs) || x.abs.startsWith(path.resolve(outDir, 'specs'))) continue;
    const p = designPath && x.arg === '--file' ? designPath : path.posix.join(prefix, 'design', path.basename(x.abs));
    if (seen.has(p)) continue;
    seen.add(p);
    files.push({ path: p, data: fs.readFileSync(x.abs) });
    if (x.arg) args.push(`${x.arg} ${p}`);
  }
  if (ci) for (const f of ciFiles(provider, { prefix, args: args.join(' ') })) files.push({ path: f.path, data: Buffer.from(f.content) });
  return files;
}

const isText = p => TEXT.has(path.extname(p).toLowerCase());

/** Git's blob id for some bytes: lets a sync skip files the remote already has. */
export const gitBlobSha = data => crypto.createHash('sha1').update(`blob ${data.length}\0`).update(data).digest('hex');

export function prBody(report, manifest, extra = '') {
  const lines = [
    `Specs and front prototype generated by **WeshCraft** from the FigCraft prototype \`${manifest.source.hash}\`.`,
    '',
    `| Parity | Screens | Components | Tokens | Entities | Operations |`,
    `|---|---|---|---|---|---|`,
    `| ${report.ok ? '✅' : '❌'} ${report.score}% (${report.checks} checks) | ${manifest.screens.length} | ${manifest.components.length} | ${manifest.tokens.variables.length} | ${manifest.domain.entities.length} | ${manifest.domain.operations.length} |`,
    '',
    '- Clickable prototype: `prototype/index.html`',
    '- Index: `specs/README.md` · parity report: `specs/PARITY.md`',
  ];
  if (!report.ok) {
    lines.push('', '<details><summary>Parity issues</summary>', '');
    for (const i of report.issues.slice(0, 50)) lines.push(`- **${i.level}** \`${i.file}\`: ${i.message}`);
    lines.push('', '</details>');
  }
  if (extra) lines.push('', extra);
  return lines.join('\n');
}

async function api(base, token, method, url, body, auth) {
  const res = await fetch(`${base}${url}`, {
    method,
    headers: {
      ...(auth === 'gitlab' ? { 'PRIVATE-TOKEN': token } : { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28' }),
      'Content-Type': 'application/json',
      'User-Agent': 'weshcraft',
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  const text = await res.text();
  let json = null;
  try { json = text ? JSON.parse(text) : null; } catch { json = { raw: text }; }
  if (!res.ok) {
    const e = new Error(`${method} ${url}: ${res.status} ${json?.message ?? json?.error ?? text.slice(0, 200)}`);
    e.status = res.status;
    throw e;
  }
  return json;
}

/**
 * @param {{repo: string, token: string, branch: string, base?: string, title: string, body: string, files: Array<{path, data}>, apiUrl?: string, message?: string, draft?: boolean}} o
 */
export async function publishGitHub(o) {
  const base = (o.apiUrl || 'https://api.github.com').replace(/\/$/, '');
  const call = (m, u, b) => api(base, o.token, m, u, b, 'github');
  const [owner, repo] = o.repo.split('/');
  if (!owner || !repo) throw new Error('GitHub repo must be owner/name');
  const R = `/repos/${owner}/${repo}`;
  const info = await call('GET', R);
  const baseBranch = o.base || info.default_branch;
  const baseRef = await call('GET', `${R}/git/ref/heads/${encodeURIComponent(baseBranch)}`);
  let parentSha;
  try {
    parentSha = (await call('GET', `${R}/git/ref/heads/${encodeURIComponent(o.branch)}`)).object.sha;
  } catch (e) {
    if (e.status !== 404) throw e;
    await call('POST', `${R}/git/refs`, { ref: `refs/heads/${o.branch}`, sha: baseRef.object.sha });
    parentSha = baseRef.object.sha;
  }
  const parent = await call('GET', `${R}/git/commits/${parentSha}`);
  const tree = [];
  for (const f of o.files) {
    if (isText(f.path)) tree.push({ path: f.path, mode: '100644', type: 'blob', content: f.data.toString('utf8') });
    else {
      const blob = await call('POST', `${R}/git/blobs`, { content: f.data.toString('base64'), encoding: 'base64' });
      tree.push({ path: f.path, mode: '100644', type: 'blob', sha: blob.sha });
    }
  }
  const newTree = await call('POST', `${R}/git/trees`, { base_tree: parent.tree.sha, tree });
  if (newTree.sha === parent.tree.sha) return { provider: 'github', changed: false, branch: o.branch, url: `${info.html_url}/tree/${o.branch}` };
  const commit = await call('POST', `${R}/git/commits`, { message: o.message || o.title, tree: newTree.sha, parents: [parentSha] });
  await call('PATCH', `${R}/git/refs/heads/${encodeURIComponent(o.branch)}`, { sha: commit.sha, force: false });
  if (o.pr === false) return { provider: 'github', changed: true, commit: commit.sha, branch: o.branch, url: `${info.html_url}/tree/${o.branch}` };
  const open = await call('GET', `${R}/pulls?state=open&head=${encodeURIComponent(`${owner}:${o.branch}`)}`);
  let pr = open[0];
  if (pr) pr = await call('PATCH', `${R}/pulls/${pr.number}`, { body: o.body });
  else pr = await call('POST', `${R}/pulls`, { title: o.title, head: o.branch, base: baseBranch, body: o.body, draft: !!o.draft });
  return { provider: 'github', changed: true, commit: commit.sha, branch: o.branch, url: pr.html_url, number: pr.number };
}

/**
 * GitLab.com or self-managed (apiUrl e.g. https://gitlab.example.com/api/v4).
 * @param {{repo: string, token: string, branch: string, base?: string, title: string, body: string, files: Array<{path, data}>, apiUrl?: string, message?: string}} o
 */
export async function publishGitLab(o) {
  const base = (o.apiUrl || 'https://gitlab.com/api/v4').replace(/\/$/, '');
  const call = (m, u, b) => api(base, o.token, m, u, b, 'gitlab');
  const P = `/projects/${encodeURIComponent(o.repo)}`;
  const project = await call('GET', P);
  const baseBranch = o.base || project.default_branch;
  let branchExists = true;
  try { await call('GET', `${P}/repository/branches/${encodeURIComponent(o.branch)}`); }
  catch (e) { if (e.status !== 404) throw e; branchExists = false; }
  const ref = branchExists ? o.branch : baseBranch;
  const existing = new Map();
  for (let page = 1; page < 200; page++) {
    const items = await call('GET', `${P}/repository/tree?recursive=true&per_page=100&page=${page}&ref=${encodeURIComponent(ref)}`).catch(e => (e.status === 404 ? [] : Promise.reject(e)));
    for (const it of items) if (it.type === 'blob') existing.set(it.path, it.id);
    if (items.length < 100) break;
  }
  // Only files whose content differs from the branch: an unchanged sync makes no commit.
  const actions = o.files.filter(f => existing.get(f.path) !== gitBlobSha(f.data)).map(f => ({
    action: existing.has(f.path) ? 'update' : 'create', file_path: f.path,
    ...(isText(f.path) ? { content: f.data.toString('utf8') } : { content: f.data.toString('base64'), encoding: 'base64' }),
  }));
  if (!actions.length && !branchExists) await call('POST', `${P}/repository/branches?branch=${encodeURIComponent(o.branch)}&ref=${encodeURIComponent(baseBranch)}`);
  if (!actions.length) return { provider: 'gitlab', changed: false, branch: o.branch, url: `${project.web_url}/-/tree/${encodeURIComponent(o.branch)}` };
  const commit = await call('POST', `${P}/repository/commits`, {
    branch: o.branch, ...(branchExists ? {} : { start_branch: baseBranch }), commit_message: o.message || o.title, actions,
  });
  if (o.pr === false) return { provider: 'gitlab', changed: true, commit: commit.id, branch: o.branch, url: `${project.web_url}/-/tree/${encodeURIComponent(o.branch)}` };
  const open = await call('GET', `${P}/merge_requests?state=opened&source_branch=${encodeURIComponent(o.branch)}`);
  let mr = open[0];
  if (mr) mr = await call('PUT', `${P}/merge_requests/${mr.iid}`, { description: o.body });
  else mr = await call('POST', `${P}/merge_requests`, { source_branch: o.branch, target_branch: baseBranch, title: o.title, description: o.body, remove_source_branch: true });
  return { provider: 'gitlab', changed: true, commit: commit.id, branch: o.branch, url: mr.web_url, number: mr.iid };
}

export function publish(provider, o) {
  if (!o.token) throw new Error(`no ${provider} access: sign in in OpenChamber, run ${provider === 'gitlab' ? 'glab' : 'gh'} auth login, or set ${provider === 'gitlab' ? 'GITLAB_TOKEN' : 'GITHUB_TOKEN'}`);
  return provider === 'gitlab' ? publishGitLab(o) : publishGitHub(o);
}
