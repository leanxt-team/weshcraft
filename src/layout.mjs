// Everything WeshCraft writes for a project lives in one folder: wcraft/.
//
//   wcraft/config.json    the project's settings: the remembered design, the spec folders
//   wcraft/design/        the design documents (FigCraft) and the surface files
//   wcraft/specs/         the generated specs
//   wcraft/prototype/     the generated prototype (clickable HTML, renders, tokens)
//   wcraft/graph.mjs      the product graph (never run; code graphs index it)
//
// Every path in this module is relative to the project root (the --out folder), and that is
// how every path is spelled everywhere else too: in the specs, in the MCP tools, in the browser
// and in the URLs. One spelling, one folder.
import fs from 'node:fs';
import path from 'node:path';

export const ROOT = 'wcraft';
export const CONFIG = `${ROOT}/config.json`;
export const DESIGN = `${ROOT}/design`;
export const SPECS = `${ROOT}/specs`;
export const PROTOTYPE = `${ROOT}/prototype`;
export const GRAPH = `${ROOT}/graph.mjs`;

/** A path inside the specs folder. */
export const spec = (...p) => path.posix.join(SPECS, ...p);
/** A path inside the prototype folder. */
export const proto = (...p) => path.posix.join(PROTOTYPE, ...p);
/** A path inside the design folder. */
export const design = (...p) => path.posix.join(DESIGN, ...p);

/** A link from one file of the project to another (relative, for markdown and HTML). */
export const link = (from, to) => path.posix.relative(path.posix.dirname(from), to);

// The layout before the wcraft folder: where older projects keep their files.
export const LEGACY = { config: '.weshcraft.json', specs: 'specs', prototype: 'prototype', design: 'design' };

const FIGCRAFT = /\.figcraft(\.json)?$/i;

/** The specs folder is ours when its manifest says so. */
function specsAreOurs(dir) {
  try {
    const m = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
    return String(m.schema ?? '').startsWith('weshcraft/manifest@');
  } catch { return false; }
}

/** The prototype is ours when it says it was generated by WeshCraft. */
function prototypeIsOurs(dir) {
  try {
    return fs.readFileSync(path.join(dir, 'index.html'), 'utf8').includes('content="weshcraft"');
  } catch { return false; }
}

/**
 * Move a project written before the wcraft folder into it: the specs, the prototype, the design
 * documents and the settings file. Nothing is ever overwritten, and nothing that is not ours is
 * touched: the specs folder must carry a WeshCraft manifest, the prototype a WeshCraft marker.
 * Safe to run again.
 * @param {string} outDir the project root
 * @param {(msg: string) => void} [log]
 * @returns {{moved: string[], relocated: Record<string, string>}} what moved, and where from
 */
export function migrate(outDir, log = () => {}) {
  const root = path.resolve(outDir);
  const moved = [];
  const relocated = {};
  const abs = rel => path.join(root, rel);
  const at = (rel, ...p) => path.join(root, rel, ...p);
  const move = (from, to) => {
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.renameSync(from, to);
    const rel = path.relative(root, to).split(path.sep).join('/');
    moved.push(rel);
    const was = path.relative(root, from).split(path.sep).join('/');
    relocated[was] = rel;
    return rel;
  };

  // The specs and the prototype: whole folders, when they are ours.
  for (const [from, to, ours] of [
    [LEGACY.specs, SPECS, specsAreOurs],
    [LEGACY.prototype, PROTOTYPE, prototypeIsOurs],
  ]) {
    if (!fs.existsSync(abs(from)) || fs.existsSync(abs(to))) continue;
    if (!ours(abs(from))) { log(`${from}/ is not a WeshCraft folder: left where it is`); continue; }
    move(abs(from), abs(to));
    log(`${from}/ → ${to}/`);
  }

  // The design documents: the FigCraft files and the product graph move into the design folder;
  // anything else in design/ stays where it is.
  if (fs.existsSync(abs(LEGACY.design))) {
    const names = fs.readdirSync(abs(LEGACY.design));
    const ours = names.filter(n => FIGCRAFT.test(n) || n === 'weshcraft.graph.mjs');
    for (const n of ours) {
      if (fs.existsSync(at(DESIGN, n))) continue;
      move(at(LEGACY.design, n), at(DESIGN, n));
    }
    if (ours.length) log(`${LEGACY.design}/*.figcraft → ${DESIGN}/`);
  }

  // The settings file: .weshcraft.json → wcraft/config.json, with the design path rewritten.
  const legacyCfg = abs(LEGACY.config);
  if (fs.existsSync(legacyCfg)) {
    let cfg = {};
    try { cfg = JSON.parse(fs.readFileSync(legacyCfg, 'utf8')); } catch { cfg = {}; }
    if (cfg.file) {
      const old = cfg.file.split(path.sep).join('/');
      if (old.startsWith(`${LEGACY.design}/`)) cfg.file = `${DESIGN}/${old.slice(LEGACY.design.length + 1)}`;
      else if (old.startsWith(`${ROOT}/`)) cfg.file = old; // already inside the folder
    }
    const target = abs(CONFIG);
    if (fs.existsSync(target)) {
      // Both exist: the new one wins, the old one only fills what it does not say.
      let cur = {};
      try { cur = JSON.parse(fs.readFileSync(target, 'utf8')); } catch { cur = {}; }
      for (const [k, v] of Object.entries(cfg)) if (cur[k] == null) cur[k] = v;
      cfg = cur;
    }
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, `${JSON.stringify(cfg, null, 2)}\n`);
    fs.rmSync(legacyCfg, { force: true });
    moved.push(CONFIG);
    relocated[LEGACY.config] = CONFIG;
    log(`${LEGACY.config} → ${CONFIG}`);
  }
  return { moved, relocated };
}
